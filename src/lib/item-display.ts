/**
 * **전시 단위 판정** — 어떤 아이템이 방 진열·NEW 피드·마켓·사이트맵에 나오는가
 * (D-211 · D-221, `FR-10-C-01·02`).
 *
 * ## ⚠️ 왜 상수 하나로 모으는가
 * D-211 이 자전거 부품을 도입하며 **4곳**(`room.ts`·`feed.ts`·`market.ts`·
 * `item.ts` 사이트맵)에 `parentId: null` 을 걸었고, 그 결정 본문이 이렇게
 * 경고했다:
 *
 * > "조회 경로가 여러 곳이므로 **한 곳이라도 빠지면 그 화면에만 샌다**"
 *
 * 운동 루틴(D-221)이 조건을 하나 더 붙였다가, D-227 이 **그 조건을 없앴다** —
 * 운동이 아이템이 아니게 되면서 "어느 루틴에도 속하지 않는다" 를 판정할 대상이
 * 사라졌다. 그래도 상수는 남긴다: 조건이 4곳에 흩어지면 **한 곳이라도 빠지면
 * 그 화면에만 새는** 성질은 그대로이고, 세 번째 구성 관계가 생기면 여기 한 줄이
 * 붙는다.
 *
 * `lib/subtype.ts` 가 "규칙은 한 곳에만 둔다"로 만든 구조와 같다 —
 * D-190(브랜드 게이트만 자체 규칙) · D-197(매칭 해석기가 두 벌) ·
 * D-202(표시 URL 과 동작 URL 이 다른 함수) · D-218 이 전부 같은 실패였다.
 *
 * ## ⚠️ "안 보인다"와 "없다"는 다르다
 * 여기 걸리지 않은 아이템도 **존재하고 수정 가능하며 도감 보유자 수에도
 * 잡힌다** (`FR-10-C-04`, D-211 Q4). 이 상수가 정하는 것은 **전시 여부**뿐이다.
 */


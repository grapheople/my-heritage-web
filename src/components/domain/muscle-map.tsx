/**
 * 근육맵 — 자극부위를 사람 실루엣에 칠한다 (D-222 · D-223 · D-238 · **D-240**).
 *
 * ## ⚠️ 왜 직접 그렸는가
 * 근육 다이어그램은 **의학 일러스트 유래가 많아 상업적 사용 조건이 갈린다.**
 * 오픈소스를 가져다 쓰면 나중에 통째로 갈아야 할 수 있다. 직접 저작하면
 * 그 위험이 **사라진다.**
 *
 * ## ⚠️ 기호이지만 **사람으로 읽혀야 한다** (D-238 → D-240)
 * 초판(D-223)은 원·둥근 사각형이었고 **로봇으로 보였다.** 2판(D-238)은 곡선
 * 실루엣을 도입해 나아졌지만, 렌더해보니 여전히 **종이 인형**이었다:
 *
 * | 결함 | 렌더에서 보인 것 |
 * |---|---|
 * | 어깨가 옷걸이 | 목 양옆에 **계단 노치**, 어깨가 수평으로 뚝 끊김 |
 * | 팔이 몸통에 겹침 | 경계가 지저분하고 **V 테이퍼가 팔에 가려 안 보였다** |
 * | 손이 없다 | 손목에서 끊기고 돌기만 남음 |
 * | 다리가 잘렸다 | 발 경로 y111.4 vs `viewBox` 112 — 바닥에서 잘림 |
 * | 가랑이가 높고 깊다 | 다리가 **독립 기둥 2개**로 보임 |
 *
 * **근본 원인은 좌표가 아니라 구조였다.** 실루엣이 조각 6종(머리·목·몸통·팔·
 * 다리·발)을 **겹쳐 놓은 것**이라 조각 경계마다 노치·계단이 생겼다. 사람
 * 실루엣은 하나의 연속 아웃라인이다.
 *
 * ## ⚠️ 그래서 실루엣은 **한 경로**다 (D-240)
 * `outline()` 이 **반신 윤곽 하나**를 받아 좌우 미러로 닫는다. 두 반신이 중심선
 * 좌표를 공유하니 **이음새가 물리적으로 존재할 수 없다.** 조각을 겹치는 방식이
 * 만들던 결함 부류가 구조적으로 사라진다.
 *
 * 자세는 **A포즈**(팔을 몸에서 약 18° 벌린 해부도 표준)다. 세 가지를 동시에
 * 해결한다: 팔과 몸통이 갈리고, **허리 V 테이퍼가 팔에 가리지 않고**, 겨드랑이·
 * 광배가 드러난다.
 *
 * ## ⚠️ `silhouette()` 의 "숫자가 곧 형태" 장점을 일부 포기했다
 * `[y, 중심x, 반폭]` 표는 읽기 좋지만 **A포즈를 표현할 수 없다** — 팔이 벌어지면
 * 한 y 에 x 구간이 3개(팔·몸통·팔) 생기므로 폭 프로파일로는 그릴 수 없다.
 * `outline()` 은 `[x, y]` 를 받아 덜 읽히므로 **구간별 주석**으로 보완한다.
 * `silhouette()` 은 근육용으로 남는다 (근육은 단일 구간이라 여전히 폭이 낫다).
 *
 * ## ⚠️ `viewBox` 는 건드리지 않았다
 * `0 0 168 112` 그대로다. A포즈로 좌우 폭이 커졌지만 손을 x 13.6~66.4, 발 밑단을
 * y 107.4 에 두어 여유 안에 넣었다 — 소비자 화면 3곳(아이템 상세·도감 상세·
 * 진열 카드)을 건드리지 않으려고. **발 잘림은 렌더로 확인했다.**
 *
 * ## ⚠️ 근육은 실루엣의 **방향을 따라간다**
 * 앞모습 승모근은 목에서 어깨로 **내려가는 사면**, 뒷모습은 **다이아몬드**,
 * 광배는 겨드랑이에서 허리로 좁아지는 **날개**, 가슴은 안쪽이 두껍고 겨드랑이로
 * 얇아지는 **방패**다. 같은 자리에 원을 얹으면 어느 부위인지 모른다.
 *
 * A포즈에서 팔 근육은 **팔의 축을 따라 기울어야 한다.** 수직으로 그리면 근육이
 * 팔에서 삐져나온다 — 그래서 `spindle()` 이 중심선 드리프트를 받고 팔 축을
 * `ARM` 상수 하나로 둔다.
 *
 * ⚠️ **근육은 실루엣을 채우지 않는다.** 재작도 중 근육 반폭을 실루엣에 가깝게
 * 잡았더니 팔이 **검은 막대**가 됐다 — 사람이 아니라 그림자로 보인다. 팔·다리는
 * 바깥으로 1~1.5 를 남긴다.
 *
 * ⚠️ **`silhouette()` 로 그릴 수 없는 근육이 있다.** 폭 프로파일은 위·아래 변이
 * 수평이라 광배처럼 "위가 넓고 아래로 모이는" 삼각을 못 만든다 — 처음엔 광배가
 * **세로 슬래브**로 보였다. 그런 근육은 경로를 손으로 적는다.
 *
 * ## ⚠️ 인접 근육이 겹치면 한 덩어리로 보인다
 * 승모근↔광배↔등중앙, 어깨↔이두/삼두가 그랬다. **둘 다 같은 루틴에서 함께
 * 켜지는 조합**이라 겹치면 "무슨 루틴인지"가 구분되지 않는다. 좌표를 잘라
 * 띄웠다 — 전부 **렌더해서 찾았고 좌표만 보고는 보이지 않았다**.
 *
 * ## ⚠️ 실루엣은 `border` 톤이다 — `muted` 가 아니다
 * 초판은 실루엣에 `fill-muted` 를 썼는데, **이 그림이 놓이는 자리가 대부분
 * `bg-muted`** 다(아이템 상세 히어로·방 진열 카드 둘 다). 같은 토큰이라
 * 실루엣이 배경에 녹아 **칠해진 부위만 공중에 떠 보였다.** 렌더해서 알았다.
 *
 * `border`(`oklch(.922 0 0)`)는 `background`(1.0)·`muted`(.97) 양쪽에서 보이고
 * 활성 `foreground`(.145)와도 충분히 갈린다.
 *
 * ## ⚠️ 무채색이다 (D-079 · DS-2)
 * "색은 아이템이 담당한다"가 이 서비스의 방향이고 `--primary` 는 검정이다.
 * 근육맵에 색을 넣으면 방 진열에서 **사진보다 근육맵이 튄다.** 활성 부위는
 * 진하게, 비활성은 옅게 — **명도만으로** 가른다. 시맨틱 토큰만 쓰므로
 * 다크 모드에서 자동으로 반전된다 (OI-44).
 *
 * ## ⚠️ 좌표만 보고 고치지 말 것
 * `pnpm muscle-preview` 가 **화면과 같은 데이터**(`BODY`·`MUSCLE_VIEWS`)를 읽어
 * 형태(900px)·구분(카드 실측)·낱개 14종을 낸다.
 *
 * | | 렌더로 찾은 결함 |
 * |---|---|
 * | D-225 | 3건 |
 * | D-238 | 6건 |
 * | D-240 | **18건** — 2판 진단 6 + 재작도 중 12 |
 *
 * **스물일곱 건 전부 좌표만 보고는 보이지 않았다.** D-240 에서는 좌표가
 * 의도대로 나오는지 **경로를 샘플링해 숫자로 검증**하기도 했다 — 그래도
 * "사람으로 보이는가"는 렌더만 답한다 (폭이 전부 맞는데 웅크려 보였다).
 *
 * ## 근육군 키는 `targetMuscle` 옵션과 **1:1** 이다
 * D-166 이 `free-exercise-db` 에서 고른 14개 그대로다. 키가 어긋나면 칠할
 * 곳을 못 찾는데 **조용히 안 칠해질 뿐**이라 알아채기 어렵다 — 그래서
 * `MUSCLE_KEYS` 를 내보내고 시드 스크립트가 이것과 대조한다.
 */

/** D-166 `targetMuscle` 옵션 14개. 시드와 **대조되는 값**이다 */
export const MUSCLE_KEYS = [
  "chest", "lats", "middleBack", "lowerBack", "shoulders", "traps",
  "biceps", "triceps", "forearms", "abdominals",
  "glutes", "quadriceps", "hamstrings", "calves",
] as const;

export type MuscleKey = (typeof MUSCLE_KEYS)[number];

type Shape =
  | { t: "e"; cx: number; cy: number; rx: number; ry: number }
  | { t: "r"; x: number; y: number; w: number; h: number; rx: number }
  /**
   * 다각형·곡선. ⚠️ `flip` 은 **좌우 반전**을 뜻한다 — 경로 좌표를 손으로
   * 뒤집는 대신 `transform` 으로 뒤집는다 (아래 `mirror` 주석 참조)
   */
  | { t: "p"; d: string; flip?: boolean };

/**
 * 한 사람의 좌표계는 **80 × 112** 다. 좌우 대칭이라 한쪽만 적고 `mirror` 로
 * 뒤집는다 — 두 벌을 적으면 한쪽만 고치는 실수가 난다.
 */
const W = 80;

/**
 * 좌우 대칭 도형을 반대편으로 옮긴다.
 *
 * ⚠️ **초판은 `path` 를 그대로 돌려줬다.** 그래서 `pair(path)` 가 **같은 도형
 * 두 개**를 만들고 광배가 **한쪽만 칠해졌다** — 예외도 경고도 없이 조용히.
 * 렌더해서 알았다 (D-225). 지금은 `flip` 을 세워 `transform` 으로 뒤집는다.
 */
function mirror(s: Shape): Shape {
  if (s.t === "e") return { ...s, cx: W - s.cx };
  if (s.t === "r") return { ...s, x: W - s.x - s.w };
  return { ...s, flip: !s.flip };
}

function pair(...shapes: Shape[]): Shape[] {
  return shapes.flatMap((s) => [s, mirror(s)]);
}

/**
 * 점들을 **중점 지나는 이차 베지어**로 잇는다 (`outline`·`silhouette` 공용).
 *
 * 각 구간의 제어점은 앞 점, 끝점은 두 점의 중간이다. 그래서 곡선은 원래 점을
 * **지나지 않고 스쳐간다** — 볼록한 꼭지가 살짝 안으로 들어온다. 대신 어디에도
 * 꺾임이 없다. 최대폭 지점은 그만큼 **넉넉히 적어야 한다** (렌더로 맞췄다).
 */
function smooth(pts: readonly (readonly [number, number])[]): string {
  let d = `M${pts[0][0]} ${pts[0][1]}`;
  for (let i = 1; i < pts.length; i++) {
    const [x, y] = pts[i];
    const [px, py] = pts[i - 1];
    d += ` Q${px} ${py} ${(px + x) / 2} ${(py + y) / 2}`;
  }
  return d;
}

/**
 * **반신 윤곽 → 좌우 대칭 전신 한 경로** (D-240).
 *
 * ## ⚠️ 왜 이것이 필요한가 — 조각 겹침이 결함의 원인이었다
 * 2판은 머리·목·몸통·팔·다리·발을 **따로 그려 겹쳤다.** 조각 경계마다 노치와
 * 계단이 생겼고(어깨가 옷걸이, 팔이 허리를 가림) 좌표를 아무리 맞춰도 옆이
 * 틀어졌다. 하나의 경로면 **경계가 없다.**
 *
 * ## 방식
 * 중심선(x=40)의 **정수리에서 시작해 오른쪽 윤곽을 일주**하고 중심선의
 * **가랑이에서 끝낸다.** 코드가 그 윤곽을 미러해 왼쪽을 잇고 닫는다.
 * 두 반신이 끝점 좌표를 공유하므로 이음새가 없다.
 *
 * ⚠️ **끝점(정수리·가랑이)은 미러 목록에서 뺀다.** 넣으면 길이 0 구간이 생겨
 * 그 자리에 꺾임이 나타난다.
 */
function outline(pts: readonly (readonly [number, number])[]): string {
  // 끝점을 뺀 나머지를 역순·미러 — 아래에서 위로 왼쪽 윤곽을 올라간다
  const left = pts.slice(1, -1).reverse().map(([x, y]) => [W - x, y] as const);
  return smooth([...pts, ...left]) + " Z";
}

/**
 * 같은 점을 두 번 놓아 **곡선이 그 점을 정확히 지나게** 한다 (D-240).
 *
 * ⚠️ `smooth` 는 중점을 지나므로 최대폭·최소폭 지점을 **스쳐 지나며 안으로
 * 잡아당긴다.** 첫 렌더에서 어깨가 좁아지고 머리가 마늘이 된 원인이 이것이었다 —
 * 좌표에는 어깨 반폭 16.2 라고 적혀 있는데 화면에서는 14 도 안 됐다.
 * 점을 겹치면 그 구간의 중점이 곧 그 점이라 **폭이 그대로 나온다.**
 *
 * 실루엣의 성격을 정하는 곳에만 쓴다: 광대 최대폭 · 삼각근 · 허리 · 골반 ·
 * 허벅지 · 종아리 · 손 · 발.
 */
function hold(x: number, y: number): (readonly [number, number])[] {
  return [
    [x, y],
    [x, y],
  ];
}

/**
 * **폭 프로파일 → 부드러운 경로.** 근육 전용이다 (실루엣은 `outline`).
 *
 * `[y, 중심x, 반폭]` 표만 적으므로 **형태가 숫자로 읽힌다** ("허벅지 4.4 →
 * 무릎 2.8"). 중심x 가 y 마다 다를 수 있어 **기울어진 팔·다리에도 쓸 수 있다** —
 * A포즈에서 근육이 팔 축을 따라가려면 이것이 필요하다 (D-240).
 *
 * ⚠️ 위·아래는 근육이 이어지는 자리라 **곧게 잇는다.** 곡선은 옆선에만 준다.
 */
type Profile = [y: number, cx: number, half: number][];

function silhouette(profile: Profile): string {
  const right = profile.map(([y, cx, h]) => [cx + h, y] as const);
  const left = [...profile].reverse().map(([y, cx, h]) => [cx - h, y] as const);
  const pts = [...right, ...left];
  const last = pts[pts.length - 1];
  return `${smooth(pts)} L${last[0]} ${last[1]} Z`;
}

/**
 * 방추형 근육(이두·삼두·전완·종아리처럼 가운데가 부푼 것).
 *
 * ⚠️ **중심선이 `cx0` → `cx1` 로 흐른다.** A포즈의 팔은 기울어 있으므로 수직
 * 방추를 얹으면 근육이 팔에서 **삐져나온다** (렌더해서 알았다, D-240).
 */
function spindle(y0: number, cx0: number, y1: number, cx1: number, maxHalf: number): string {
  const steps = 7;
  const profile: Profile = Array.from({ length: steps + 1 }, (_, i) => {
    const t = i / steps;
    // sin 곡선으로 양 끝이 좁고 가운데가 두껍다. 끝을 완전히 0 으로 만들지 않는다
    const half = maxHalf * (0.38 + 0.62 * Math.sin(Math.PI * t));
    return [y0 + (y1 - y0) * t, cx0 + (cx1 - cx0) * t, half];
  });
  return silhouette(profile);
}

